"""The coverage tables of the taxonomy, generated from the case tags.

Each development case in `evals/cases.json` says which decision boundaries
it was built to exercise (`covers`) and which invariances it checks
(`invariance`). This module checks those tags against the boundaries
`evals/taxonomy.md` defines, and writes the tables of its section 6 from
them, between two markers -- so the tables say what the tags say, and a tag
that changes without the tables fails CI:

    python -m evals.coverage          # rewrite the tables
    python -m evals.coverage --check  # fail if a tag is invalid or a table stale

A tag records what a case was built to exercise, as the maintainer
adjudicated it; it is not proof that a run checks it. The runner's own
assertion limits still apply (taxonomy, L11).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CASES_PATH = ROOT / "cases.json"
TAXONOMY_PATH = ROOT / "taxonomy.md"

BEGIN = "<!-- coverage:begin -- generated by `python -m evals.coverage`; do not edit -->"
END = "<!-- coverage:end -->"

#: The taxonomy's test types, and EX: a plain example, built as no controlled
#: variation of another case.
TYPES = ("CP", "BV", "MU", "AD", "ML", "CD", "CO", "EX")
#: Types that name the case they vary from.
NEEDS_PARTNER = frozenset({"CP", "MU"})
SIDES = frozenset({"A", "B", "X"})
INVARIANCES = ("I1", "I2", "I3", "I4", "I5")
#: Every case sits on one side of B23 (financial vs non-financial action);
#: membership is not a check, so B23 is reported from the expectations instead.
UNTAGGED = frozenset({"B23"})
FINANCIAL = frozenset({"credit_note", "refund"})

_BOUNDARY = re.compile(r"^\*\*(B\d+) — (.+?)\*\* · (.+)$")
_TESTS = re.compile(r"^- Tests: (.+)$")


@dataclass(frozen=True)
class Boundary:
    id: str
    title: str
    sided: bool  # names sides A and B, rather than one rule and its outcomes
    called_for: tuple[str, ...]  # test types the taxonomy asks for


def boundaries(taxonomy: str) -> dict[str, Boundary]:
    """The boundaries of section 1, in the order they are written."""
    section = taxonomy.split("\n## 2. Invariances")[0]
    found: dict[str, Boundary] = {}
    for block in re.split(r"\n(?=\*\*B\d+ — )", section):
        lines = block.strip().splitlines()
        head = _BOUNDARY.match(lines[0]) if lines else None
        if head is None:
            continue
        sided = any(re.match(r"^- A: |^A: ", line) for line in lines)
        called: tuple[str, ...] = ()
        for line in lines:
            tests = _TESTS.match(line)
            if tests:
                called = tuple(t for t in TYPES if re.search(rf"\b{t}\b", tests.group(1)))
        found[head.group(1)] = Boundary(head.group(1), head.group(2), sided, called)
    return found


def problems(cases: list[dict], known: dict[str, Boundary]) -> list[str]:
    """Every tag that does not fit; empty when all do."""
    ids = {case["id"] for case in cases}
    found = []
    for case in cases:
        name = case["id"]
        covers = case.get("covers")
        if not isinstance(covers, list) or not covers:
            found.append(f"{name}: no `covers`")
            continue
        for tag in covers:
            found.extend(f"{name}: {p}" for p in _tag_problems(tag, known, ids))
        for inv in case.get("invariance", []):
            if inv not in INVARIANCES:
                found.append(f"{name}: unknown invariance {inv!r}")
    return found


def _tag_problems(tag: object, known: dict[str, Boundary], ids: set[str]) -> list[str]:
    if not isinstance(tag, dict):
        return ["a tag is not an object"]
    boundary = known.get(tag.get("boundary", ""))
    if boundary is None or boundary.id in UNTAGGED:
        return [f"unknown or untaggable boundary {tag.get('boundary')!r}"]
    found = []
    if tag.get("type") not in TYPES:
        found.append(f"{boundary.id}: unknown type {tag.get('type')!r}")
    side = tag.get("side")
    if boundary.sided and side not in SIDES:
        found.append(f"{boundary.id}: a side A, B or X is required")
    if not boundary.sided and side is not None:
        found.append(f"{boundary.id}: states one rule and has no sides")
    if side == "X" and not tag.get("outcome"):
        found.append(f"{boundary.id}: side X names its outcome")
    partner = tag.get("with")
    if tag.get("type") in NEEDS_PARTNER and not partner:
        found.append(f"{boundary.id}: {tag.get('type')} names the case it varies from")
    if partner is not None and partner not in ids:
        found.append(f"{boundary.id}: partner {partner!r} is not a case")
    if partner is not None and not tag.get("varies"):
        found.append(f"{boundary.id}: a partner comes with what `varies`")
    if tag.get("asserts", "decision") not in ("decision", "finding"):
        found.append(f"{boundary.id}: `asserts` is decision or finding")
    return found


def render(cases: list[dict], known: dict[str, Boundary]) -> str:
    """The generated part of section 6, markers included."""
    rows = {b: {"A": [], "B": [], "X": [], "rule": []} for b in known}
    types: dict[str, dict[str, set[str]]] = {b: {t: set() for t in TYPES} for b in known}
    for case in cases:
        for tag in case["covers"]:
            b = tag["boundary"]
            label = f"`{case['id']}`"
            if tag.get("asserts") == "finding":
                label += " (finding)"
            if tag.get("outcome"):
                label += f" ({tag['outcome'].replace('_', ' ')})"
            rows[b][tag.get("side", "rule")].append(label)
            types[b][tag["type"]].add(case["id"])

    out = [BEGIN, "", "### Cases by boundary", ""]
    out.append("| | Boundary | Side A | Side B | Outside A and B | Called for | Exercised |")
    out.append("|---|---|---|---|---|---|---|")
    for b in known.values():
        if b.id in UNTAGGED:
            continue
        r = rows[b.id]
        side_a = ", ".join(r["A"]) or ("not listed" if b.sided else "")
        if not b.sided:
            side_a = "*one rule:* " + (", ".join(r["rule"]) or "none")
        side_b = ", ".join(r["B"]) or ("none" if b.sided else "")
        exercised = ", ".join(t for t in TYPES if types[b.id][t]) or "none"
        out.append(
            f"| {b.id} | {b.title} | {side_a} | {side_b} | {', '.join(r['X'])} "
            f"| {', '.join(b.called_for)} | {exercised} |"
        )

    out += ["", "### Boundaries by test type", ""]
    out.append(
        "Cases per cell. **0** marks a type the boundary calls for with no case; "
        "an empty cell, a type it does not call for and no case uses."
    )
    out += ["", "| | " + " | ".join(TYPES) + " |", "|---|" + "---|" * len(TYPES)]
    for b in known.values():
        if b.id in UNTAGGED:
            continue
        cells = []
        for t in TYPES:
            n = len(types[b.id][t])
            cells.append(str(n) if n else ("**0**" if t in b.called_for else ""))
        out.append(f"| {b.id} | " + " | ".join(cells) + " |")

    out += ["", "### B23, from the expectations", ""]
    financial = [c for c in cases if c["expect_action"] in FINANCIAL]
    others = [c for c in cases if c["expect_action"] not in FINANCIAL]
    out.append(
        f"Financial action expected: {len(financial)} cases, "
        f"{sum(c['expect_human_approval'] for c in financial)} with human approval. "
        f"Non-financial: {len(others)} cases, "
        f"{sum(not c['expect_human_approval'] for c in others)} without approval and "
        f"{sum(c['expect_human_approval'] for c in others)} sent to a person anyway."
    )

    out += ["", "### Invariances", ""]
    for inv in INVARIANCES:
        named = [f"`{c['id']}`" for c in cases if inv in c.get("invariance", [])]
        out.append(f"- {inv}: {', '.join(named) or 'none'}")
    out += ["", END]
    return "\n".join(out)


def updated(taxonomy: str, block: str) -> str:
    start, end = taxonomy.index(BEGIN), taxonomy.index(END) + len(END)
    return taxonomy[:start] + block + taxonomy[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    args = parser.parse_args()

    cases = json.loads(CASES_PATH.read_text(encoding="utf-8"))
    taxonomy = TAXONOMY_PATH.read_text(encoding="utf-8")
    known = boundaries(taxonomy)
    if found := problems(cases, known):
        print("\n".join(found), file=sys.stderr)
        return 1
    fresh = updated(taxonomy, render(cases, known))
    if args.check:
        if fresh != taxonomy:
            print("evals/taxonomy.md is stale: run `python -m evals.coverage`", file=sys.stderr)
            return 1
        print("coverage tables: up to date")
        return 0
    TAXONOMY_PATH.write_text(fresh, encoding="utf-8", newline="\n")
    print("coverage tables written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
